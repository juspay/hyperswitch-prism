/// The header HiPay carries the notification signature in (`HTTP_X_ALLOPASS_SIGNATURE` in PHP).
/// HTTP header names are case-insensitive and the gRPC caller forwards whatever casing the
/// notification arrived with, so the lookup below folds case rather than matching this literal.
/// spec:### Webhook Authentication & Signature Verification
pub(crate) const HIPAY_WEBHOOK_SIGNATURE_HEADER: &str = "x-allopass-signature";

/// The notification signature, case-insensitively by header name and lowercased for comparison.
///
/// Returns `None` for an absent or blank header, a non-hex value, or a digest whose length is not
/// one of HiPay's three configurable algorithms — every one of which is a fail-closed refusal in
/// [`verify_webhook_source`] (G-IncomingWebhook-01 / G-IncomingWebhook-02). The value itself is
/// never logged.
fn hipay_signature_hex(request: &connector_types_webhook::RequestDetails) -> Option<String> {
    let received = request
        .headers
        .iter()
        .find(|(name, _)| name.eq_ignore_ascii_case(HIPAY_WEBHOOK_SIGNATURE_HEADER))
        .map(|(_, value)| value.trim().to_ascii_lowercase())?;
    if received.is_empty() || !received.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    Some(received)
}

/// `HASH(raw POST body ‖ secret passphrase)` as lowercase hex, with the algorithm selected from
/// the length of the digest HiPay sent.
///
/// HiPay's back office lets the merchant pick SHA-256 (the documented default), SHA-1 or SHA-512
/// and exposes **no API to discover which is in force**, so the algorithm cannot be a constant and
/// cannot be configured without a new credential field (UD-02 rejected that). The received digest
/// length is the only deterministic signal: 40 hex characters is SHA-1, 64 is SHA-256, 128 is
/// SHA-512. Anything else returns `None`, which is a refusal — never a guess and never a pass.
///
/// `common_utils::crypto` provides the SHA-256 and SHA-512 digests; it has no SHA-1, so that one
/// leg calls the same `ring` primitive `common_utils::crypto` itself wraps rather than
/// hand-rolling a hash.
/// spec:## 10. Signature / MAC (HMAC) rules #### A. Server-to-server notifications (webhooks)
fn hipay_expected_signature_hex(preimage: &[u8], received_hex_len: usize) -> Option<String> {
    use common_utils::crypto::{GenerateDigest, Sha256, Sha512};
    let digest = match received_hex_len {
        40 => ring::digest::digest(&ring::digest::SHA1_FOR_LEGACY_USE_ONLY, preimage)
            .as_ref()
            .to_vec(),
        64 => Sha256.generate_digest(preimage).ok()?,
        128 => Sha512.generate_digest(preimage).ok()?,
        _ => return None,
    };
    Some(hex::encode(digest))
}

/// Compare two digests without an early exit on the first differing byte.
///
/// Both operands here are lowercase hex of the same length, so this folds every byte before it
/// answers. It is a byte comparison, not a hash: the digests themselves come from
/// `common_utils::crypto` / `ring`. `ring::constant_time::verify_slices_are_equal` is deprecated
/// in the pinned `ring` and fails `-D warnings`, and the workspace has no `subtle` dependency.
fn fixed_time_eq(left: &[u8], right: &[u8]) -> bool {
    left.len() == right.len()
        && left
            .iter()
            .zip(right.iter())
            .fold(0u8, |acc, (l, r)| acc | (l ^ r))
            == 0
}

/// Parse the raw notification bytes as HiPay's XML notification.
///
/// `quick_xml::de` deserializes the document element into the struct without matching its name,
/// which is what makes the undocumented root element a non-problem. Every failure is a checked
/// error: this parser reads untrusted, externally supplied bytes, so nothing here may panic. The
/// raw body is deliberately absent from the error context — it carries a masked PAN, a cardholder
/// name and a customer email.
/// spec:### IncomingWebhook > DOCUMENTATION GAP — Content-Type and XML root
fn hipay_notification_from_body(
    body: &[u8],
) -> Result<hipay::HipayWebhookNotification, error_stack::Report<WebhookError>> {
    use common_utils::ext_traits::XmlExt;
    let document = std::str::from_utf8(body)
        .map_err(|_| error_stack::report!(WebhookError::WebhookBodyDecodingFailed))
        .attach_printable(
            "HiPay notification body is not valid UTF-8; HiPay POSTs an XML document to the \
             merchant notify_url",
        )?;
    document
        .parse_xml::<hipay::HipayWebhookNotification>()
        .map_err(|error| {
            error_stack::report!(WebhookError::WebhookBodyDecodingFailed).attach_printable(format!(
                "Failed to parse the HiPay XML notification ({error}); `state`, `status` and \
                 `transaction_reference` are required elements. The body is not reproduced here \
                 because it carries card and personal data."
            ))
        })
}

/// The transaction reference a notification is keyed on.
///
/// This is `transaction_reference`, the value Authorize returned as `connector_transaction_id` —
/// **not** `order[id]`, which is the merchant's own `orderid` and would resolve against no stored
/// payment. A blank reference is refused rather than passed on as an empty string.
/// spec:### IncomingWebhook (Phase 1); hs:crates/hyperswitch_connectors/src/connectors/hipay/transformers.rs:186
fn hipay_webhook_reference(
    notification: &hipay::HipayWebhookNotification,
) -> Result<String, error_stack::Report<WebhookError>> {
    notification
        .non_empty_transaction_reference()
        .map(str::to_owned)
        .ok_or_else(|| {
            error_stack::report!(WebhookError::WebhookReferenceIdNotFound).attach_printable(
                "HiPay notification carries a blank `transaction_reference`; it is the only \
                 element that resolves the notification to a stored payment",
            )
        })
}

/// `(error_code, error_message, error_reason)` for a notification whose event type is a failure.
///
/// The decline detail comes from the `reason` object through the shared `40xxxxx`-band rule, so
/// the notification path reports the acquirer / issuer code exactly as the synchronous paths do.
/// A failure with no `reason` object still reports an explicit code and message rather than an
/// empty string (INV-07 / INV-17): `WebhookDetailsResponse` and `RefundWebhookDetailsResponse`
/// carry no `network_decline_code` / `network_error_message` pair, so `error_code` and
/// `error_message` are where those values land.
/// spec:### Transaction-level decline detail (reason object); spec:## 9. Error / decline reason codes
fn hipay_webhook_error_fields(
    notification: &hipay::HipayWebhookNotification,
    is_failure: bool,
) -> (Option<String>, Option<String>, Option<String>) {
    if !is_failure {
        return (None, None, None);
    }
    let (network_decline_code, network_error_message) = notification.network_fields();
    let message = notification
        .message
        .as_ref()
        .map(|message| message.trim().to_owned())
        .filter(|message| !message.is_empty());
    (
        Some(network_decline_code.unwrap_or_else(|| NO_ERROR_CODE.to_string())),
        Some(
            network_error_message
                .or_else(|| message.clone())
                .unwrap_or_else(|| NO_ERROR_MESSAGE.to_string()),
        ),
        message,
    )
}

/// HiPay server-to-server notifications.
///
/// Not a `ConnectorIntegrationV2` flow: no `connector_flow` marker, no macro. Two RPCs, two
/// phases — `EventService.ParseEvent` is stateless (`get_event_type` +
/// `get_webhook_event_reference`) and `EventService.HandleEvent` is the one that sees secrets
/// (`verify_webhook_source`, then `process_*_webhook`).
/// spec:### IncomingWebhook
impl<T: PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize>
    connector_types::IncomingWebhook for Hipay<T>
{
    /// **G-IncomingWebhook-01 / G-IncomingWebhook-02 — fail closed.**
    ///
    /// HiPay's only inbound authentication is `x-allopass-signature` =
    /// `HASH(raw POST body ‖ secret passphrase)`. The preimage is order-sensitive and is taken
    /// over the **raw** bytes: nothing is decoded, re-serialised or normalised first.
    ///
    /// `Ok(false)` — never `Ok(true)`, never an error that a caller might read as "unverifiable,
    /// carry on" — is returned when the header is absent, blank or not hex; when no webhook
    /// secret reached the request; or when the digest length is not one of HiPay's three
    /// configurable algorithms. Nothing about the body, the signature or the passphrase is logged.
    ///
    /// The redirect-page `hash` parameter is a **different** scheme (a hash over alphabetically
    /// sorted parameters) and is deliberately not reachable from here.
    /// spec:## 10. Signature / MAC (HMAC) rules #### A; spec:### Webhook Authentication & Signature Verification
    fn verify_webhook_source(
        &self,
        request: connector_types_webhook::RequestDetails,
        connector_webhook_secret: Option<connector_types_webhook::ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
    ) -> Result<bool, error_stack::Report<WebhookError>> {
        // G-IncomingWebhook-01a — no passphrase, no verification.
        let Some(secrets) = connector_webhook_secret.filter(|s| !s.secret.is_empty()) else {
            tracing::warn!(
                target: "hipay_webhook",
                "HiPay notification rejected: no webhook secret reached verify_webhook_source. \
                 The back-office notification passphrase (TPP > Integration > Security Settings) \
                 must be supplied as WebhookSecrets.secret on EventService.HandleEvent."
            );
            return Ok(false);
        };

        // G-IncomingWebhook-01b — no signature header, no verification.
        let Some(received) = hipay_signature_hex(&request) else {
            tracing::warn!(
                target: "hipay_webhook",
                header = HIPAY_WEBHOOK_SIGNATURE_HEADER,
                "HiPay notification rejected: the signature header is absent, blank or not \
                 hexadecimal. It is the only carrier of the notification signature."
            );
            return Ok(false);
        };

        let mut preimage = Vec::with_capacity(request.body.len() + secrets.secret.len());
        preimage.extend_from_slice(&request.body);
        preimage.extend_from_slice(&secrets.secret);

        // G-IncomingWebhook-02 — an unrecognised digest length means the algorithm cannot be
        // selected, so the digest cannot be reproduced and the notification cannot be trusted.
        let Some(expected) = hipay_expected_signature_hex(&preimage, received.len()) else {
            tracing::warn!(
                target: "hipay_webhook",
                digest_hex_length = received.len(),
                "HiPay notification rejected: the signature digest length matches none of the \
                 three algorithms HiPay's back office can be configured with (40 = SHA-1, \
                 64 = SHA-256, 128 = SHA-512)."
            );
            return Ok(false);
        };

        Ok(fixed_time_eq(expected.as_bytes(), received.as_bytes()))
    }

    /// A minimal, structurally valid HiPay notification, for the field probe.
    fn sample_webhook_body(&self) -> &'static [u8] {
        br#"<?xml version="1.0" encoding="UTF-8"?><operation><state>completed</state><status>118</status><message>Captured</message><transaction_reference>800000000001</transaction_reference><currency>EUR</currency><captured_amount>1.00</captured_amount><order><id>probe_order_001</id></order></operation>"#
    }

    /// **Phase 1 — `EventService.ParseEvent`.** Stateless: the event class is decided by the
    /// numeric `status` alone, because HiPay has no event-type field and **no separate dispute
    /// webhook** — a chargeback is an ordinary transaction notification carrying 180 / 181 / 134.
    /// spec:### IncomingWebhook (Phase 1); spec:## Status Mappings ### Notified statuses
    fn get_event_type(
        &self,
        request: connector_types_webhook::RequestDetails,
    ) -> Result<connector_types_webhook::EventType, error_stack::Report<WebhookError>> {
        let notification = hipay_notification_from_body(&request.body)?;
        Ok(hipay::hipay_webhook_event_type(&notification))
    }

    /// **Phase 1 — `EventService.ParseEvent`.** The event reference is `transaction_reference`,
    /// the value the payment side stores as `connector_transaction_id`. `order[id]` is the
    /// merchant's own `orderid` and travels as the merchant-side reference, never as the event
    /// reference — keying on it is the trap the scout recorded for this connector.
    /// spec:### IncomingWebhook (Phase 1); spec:### Refunds > DOCUMENTATION GAP — no refund-level identifier
    fn get_webhook_event_reference(
        &self,
        request: connector_types_webhook::RequestDetails,
    ) -> Result<
        Option<connector_types_webhook::WebhookResourceReference>,
        error_stack::Report<WebhookError>,
    > {
        let notification = hipay_notification_from_body(&request.body)?;
        let reference = hipay_webhook_reference(&notification)?;
        let merchant_reference = notification.order_reference();

        Ok(Some(match notification.status.event_class() {
            hipay::HipayWebhookEventClass::Payment => {
                connector_types_webhook::WebhookResourceReference::Payment(
                    connector_types_webhook::PaymentWebhookReference {
                        connector_transaction_id: Some(reference),
                        merchant_transaction_id: merchant_reference,
                    },
                )
            }
            // HiPay issues no refund-level identifier: the refund is addressed by the ORIGINAL
            // transaction reference, and `operation[id]` — the merchant `operation_id` echoed
            // back — is the only thing that says which refund this is.
            hipay::HipayWebhookEventClass::Refund => {
                connector_types_webhook::WebhookResourceReference::Refund(
                    connector_types_webhook::RefundWebhookReference {
                        connector_refund_id: Some(reference.clone()),
                        merchant_refund_id: notification.operation_reference(),
                        connector_transaction_id: Some(reference),
                        merchant_transaction_id: merchant_reference,
                    },
                )
            }
            // There is no HiPay dispute id, so the disputed payment's reference identifies the
            // case on both sides.
            hipay::HipayWebhookEventClass::Dispute => {
                connector_types_webhook::WebhookResourceReference::Dispute(
                    connector_types_webhook::DisputeWebhookReference {
                        connector_dispute_id: Some(reference.clone()),
                        connector_transaction_id: Some(reference),
                    },
                )
            }
        }))
    }

    /// **Phase 2 Step B — payment notification.** The status is mapped through the *same*
    /// `HipayPaymentStatus` -> `AttemptStatus` table the Authorize, Capture, Void and PSync paths
    /// use, so no status can mean one thing on the sync path and another here.
    /// spec:### IncomingWebhook (Phase 2 Step B); spec:## Status Mappings ### Notified statuses
    fn process_payment_webhook(
        &self,
        request: connector_types_webhook::RequestDetails,
        _connector_webhook_secret: Option<connector_types_webhook::ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
        _event_context: Option<connector_types_webhook::EventContext>,
    ) -> Result<connector_types_webhook::WebhookDetailsResponse, error_stack::Report<WebhookError>>
    {
        let notification = hipay_notification_from_body(&request.body)?;
        let reference = hipay_webhook_reference(&notification)?;
        let status = common_enums::AttemptStatus::from(notification.status.payment_status());
        let is_failure = matches!(
            hipay::hipay_webhook_event_type(&notification),
            connector_types_webhook::EventType::PaymentIntentFailure
                | connector_types_webhook::EventType::PaymentIntentAuthorizationFailure
                | connector_types_webhook::EventType::PaymentIntentCaptureFailure
                | connector_types_webhook::EventType::PaymentIntentCancelFailure
        );
        let (error_code, error_message, error_reason) =
            hipay_webhook_error_fields(&notification, is_failure);
        let minor_amount_captured = notification.captured_amount_minor();

        Ok(connector_types_webhook::WebhookDetailsResponse {
            resource_id: Some(
                domain_types::connector_types::ResponseId::ConnectorTransactionId(reference),
            ),
            status,
            // `order[id]` — the merchant's own reference, echoed back.
            connector_response_reference_id: notification.order_reference(),
            connector_request_reference_id: None,
            // The reusable vault token, inside a `SecretSerdeValue`, exactly as the Mandates legs
            // carry it.
            mandate_reference: notification.mandate_reference(),
            error_code,
            error_message,
            error_reason,
            // Deliberately not the raw body: the notification carries a masked PAN, a cardholder
            // name and a customer email, and this field is not masked downstream.
            raw_connector_response: None,
            status_code: 200,
            response_headers: None,
            amount_captured: minor_amount_captured.map(|amount| amount.get_amount_as_i64()),
            minor_amount_captured,
            // HiPay's scheme reference data / TLID appear only on the V3 `debitAgreement` object,
            // never on a notification.
            network_txn_id: None,
            // `payment_method[*]` -> the framework's own card-detail update.
            payment_method_update: notification.card_detail_update(),
            sender_payment_instrument_id: None,
            connector_returned_payment_method_details: None,
        })
    }

    /// **Phase 2 Step B — refund notification.** The same notification shape, read through the
    /// `HipayRefundStatus` table the Refund and RSync paths use (124/125/126/165 plus the RDR
    /// refunds 182/183). `operation[id]` is the only correlator for an individual partial refund,
    /// because HiPay issues no refund-level identifier.
    /// spec:### IncomingWebhook (Refund webhooks); spec:### Refunds > DOCUMENTATION GAP
    fn process_refund_webhook(
        &self,
        request: connector_types_webhook::RequestDetails,
        _connector_webhook_secret: Option<connector_types_webhook::ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
    ) -> Result<
        connector_types_webhook::RefundWebhookDetailsResponse,
        error_stack::Report<WebhookError>,
    > {
        let notification = hipay_notification_from_body(&request.body)?;
        let reference = hipay_webhook_reference(&notification)?;
        let status = common_enums::RefundStatus::from(notification.status.refund_status());
        let (error_code, error_message, _) = hipay_webhook_error_fields(
            &notification,
            matches!(status, common_enums::RefundStatus::Failure),
        );

        Ok(connector_types_webhook::RefundWebhookDetailsResponse {
            // The ORIGINAL transaction reference — the same value the Refund and RSync paths
            // write as `connector_refund_id` (UD-04).
            connector_refund_id: Some(reference),
            merchant_transaction_id: notification.order_reference(),
            status,
            // The merchant `operation_id` HiPay echoes back, when the maintenance call sent one.
            connector_response_reference_id: notification.operation_reference(),
            error_code,
            error_message,
            raw_connector_response: None,
            status_code: 200,
            response_headers: None,
        })
    }

    /// **Phase 2 Step B — chargeback notification.** HiPay has no separate dispute webhook: 181
    /// Chargeback and 180 Partially Chargeback arrive as ordinary transaction notifications and
    /// open a dispute, 134 Dispute Lost closes it against the merchant. There is **no "dispute
    /// won" status in HiPay's vocabulary**, and none is invented here.
    /// spec:### IncomingWebhook (Dispute webhooks); spec:### IncomingWebhook > DOCUMENTATION GAP — dispute lifecycle
    fn process_dispute_webhook(
        &self,
        request: connector_types_webhook::RequestDetails,
        _connector_webhook_secret: Option<connector_types_webhook::ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
    ) -> Result<
        connector_types_webhook::DisputeWebhookDetailsResponse,
        error_stack::Report<WebhookError>,
    > {
        let notification = hipay_notification_from_body(&request.body)?;
        let reference = hipay_webhook_reference(&notification)?;
        let (minor_amount, currency) = notification.disputed_amount_minor().ok_or_else(|| {
            error_stack::report!(WebhookError::WebhookProcessingFailed).attach_printable(
                "HiPay chargeback notification carries no amount/currency pair; a dispute is \
                 reported with the amount that moved, so `currency` plus one of \
                 `refunded_amount` / `captured_amount` / `authorized_amount` is required",
            )
        })?;
        let (network_decline_code, _) = notification.network_fields();

        Ok(connector_types_webhook::DisputeWebhookDetailsResponse {
            amount: domain_types::utils::convert_amount_for_webhook(
                &common_utils::types::StringMinorUnitForConnector,
                minor_amount,
                currency,
            )?,
            currency,
            // HiPay issues no dispute identifier — the disputed payment's reference is the only
            // handle the notification carries.
            dispute_id: reference,
            status: common_enums::DisputeStatus::from(notification.status.dispute_status()),
            stage: common_enums::DisputeStage::Dispute,
            connector_response_reference_id: notification.order_reference(),
            dispute_message: notification
                .message
                .as_ref()
                .map(|message| message.trim().to_owned())
                .filter(|message| !message.is_empty()),
            raw_connector_response: None,
            status_code: 200,
            response_headers: None,
            connector_reason_code: network_decline_code,
        })
    }
}
