/// G-Payments-03 — HiPay's maintenance and V3 consultation endpoints take the transaction
/// reference as a **path segment**, so an absent or blank reference would address the
/// collection URL rather than the transaction.
/// spec:#### 2. Maintenance (Capture / Refund / Void); spec:#### 3. Transaction Lookup
pub(crate) fn non_empty_transaction_reference(
    transaction_reference: Option<String>,
) -> CustomResult<String, IntegrationError> {
    transaction_reference
        .filter(|reference| !reference.trim().is_empty())
        .ok_or_else(|| {
            error_stack::Report::new(IntegrationError::MissingConnectorTransactionID {
                context: domain_types::errors::IntegrationErrorContext {
                    suggested_action: Some(
                        "Send the transactionReference HiPay returned on the authorize call."
                            .to_string(),
                    ),
                    doc_url: None,
                    additional_context: Some(
                        "HiPay addresses a transaction by reference in the URL path; an empty                          value would request the collection endpoint."
                            .to_string(),
                    ),
                },
            })
        })
}

