impl<T: PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize> ConnectorCommon
    for Hipay<T>
{
    fn id(&self) -> &'static str {
        "hipay"
    }

    fn get_currency_unit(&self) -> CurrencyUnit {
        CurrencyUnit::Base
    }

    fn base_url<'a>(&self, connectors: &'a Connectors) -> &'a str {
        connectors.hipay.base_url.as_ref()
    }

    fn get_auth_header(
        &self,
        auth_type: &ConnectorSpecificConfig,
    ) -> CustomResult<Vec<(String, Maskable<String>)>, IntegrationError> {
        let auth = hipay::HipayAuthType::try_from(auth_type).change_context(
            IntegrationError::FailedToObtainAuthType {
                context: domain_types::errors::IntegrationErrorContext {
                    suggested_action: Some(
                        "Configure the HiPay connector with its API username (api_key) and \
                         password (api_secret)."
                            .to_string(),
                    ),
                    doc_url: None,
                    additional_context: Some(
                        "HiPay authenticates every call with HTTP Basic credentials from the \
                         merchant's back office."
                            .to_string(),
                    ),
                },
            },
        )?;

        // Use HTTP Basic Auth for HiPay
        use base64::Engine;
        let credentials = format!("{}:{}", auth.api_key.expose(), auth.api_secret.expose());
        let base64_credentials = base64::engine::general_purpose::STANDARD.encode(credentials);
        let auth_value = format!("Basic {base64_credentials}");

        // `.into_masked()` (not a bare `.into()`): the event serialiser in
        // `crates/common/common_utils/src/events.rs` prints `Maskable::Normal` verbatim and only
        // redacts `Maskable::Masked`, so a bare `.into()` here writes
        // `base64(api_key:api_secret)` in clear into every request log line and echoes it in
        // `rawConnectorRequest` on the API response.
        Ok(vec![(
            headers::AUTHORIZATION.to_string(),
            auth_value.into_masked(),
        )])
    }

    fn build_error_response(
        &self,
        res: Response,
        event_builder: Option<&mut events::Event>,
        _connector_config: &ConnectorSpecificConfig,
    ) -> CustomResult<ErrorResponse, ConnectorError> {
        let error_response: hipay::HipayErrorResponse = res
            .response
            .parse_struct("HipayErrorResponse")
            .unwrap_or_else(|_| {
                let raw_response = String::from_utf8_lossy(&res.response);
                let message = if raw_response.trim().is_empty() {
                    "Unknown error from HiPay".to_string()
                } else if raw_response.len() > 200 {
                    format!("{}...", &raw_response[..200])
                } else {
                    raw_response.to_string()
                };

                hipay::HipayErrorResponse {
                    code: hipay::HipayErrorCode::Numeric(i64::from(res.status_code)),
                    message,
                    description: None,
                }
            });

        with_error_response_body!(event_builder, error_response);

        let typed =
            macros::serialize_typed_connector_payload(&error_response, "typed_connector_response");
        Ok(ErrorResponse {
            status_code: res.status_code,
            code: error_response.code.to_string(),
            message: error_response.message.clone(),
            // `description` carries HiPay's actionable detail; fall back to `message` only when
            // the envelope did not include one.
            reason: error_response
                .description
                .clone()
                .or_else(|| Some(error_response.message.clone())),
            // Left unset on the transport-error path: the flow-specific `handle_response_v2`
            // conversions own the attempt status, and a 4xx/5xx here says nothing about the
            // attempt beyond what the caller already knows.
            attempt_status: None,
            connector_transaction_id: None,
            network_decline_code: None,
            network_advice_code: None,
            network_error_message: None,
            typed_connector_response: typed,
            raw_connector_response: None,
            raw_connector_request: None,
            typed_connector_request: None,
        })
    }
}

