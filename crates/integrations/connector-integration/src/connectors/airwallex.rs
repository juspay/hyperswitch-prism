impl<T: PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize>
    connector_types::ValidationTrait for Airwallex<T>
{
    fn should_do_access_token(&self, _payment_method: Option<common_enums::PaymentMethod>) -> bool {
        true
    }

    fn should_do_order_create(&self) -> bool {
        true // Enable 2-step flow: ServerAuthenticationToken → CreateOrder → Authorize
    }

    /// Drives the composite authorize loop through Airwallex's two-call 3DS journey for
    /// card + ThreeDs: `PreAuthenticate` (`POST .../confirm`) → Airwallex-hosted redirect →
    /// `PostAuthenticate` (`GET .../{id}`) → `Authorize` (which, having a `redirect_response`, is
    /// itself a `GET` retrieve — see `transformers::is_card_three_ds_continue`).
    ///
    /// **No arm returns [`AuthenticationStep::Authenticate`], and that is deliberate.** On the
    /// pinned API version Airwallex runs the 3DS method call and the ACS challenge inside its own
    /// hosted page; there is no merchant-issued call between `confirm` and the browser's return.
    /// `PaymentAuthenticateV2` is therefore not implemented and `Authenticate` stays in
    /// `not_implemented`. Because Airwallex's `confirm` *is* the authorization, any arm that led
    /// to a second `confirm` would be a double charge.
    ///
    /// Termination: `PreAuthenticate` breaks the loop itself when it returns a redirect, and both
    /// `Some(PreAuthenticate)` and `Some(PostAuthenticate)` resolve to `Authorize`, which is the
    /// loop's unconditional exit. `PostAuthenticate` never breaks on its own, so the
    /// `Some(PostAuthenticate) => Authorize` arm is mandatory.
    ///
    /// [`AuthenticationStep::Authenticate`]: connector_types::AuthenticationStep::Authenticate
    fn next_authentication_step(
        &self,
        auth_type: common_enums::AuthenticationType,
        payment_method: common_enums::PaymentMethod,
        redirect_state: connector_types::RedirectState,
        completed_step: Option<connector_types::AuthenticationStep>,
    ) -> connector_types::AuthenticationStep {
        use connector_types::{AuthenticationStep, RedirectState};

        if auth_type != common_enums::AuthenticationType::ThreeDs
            || payment_method != common_enums::PaymentMethod::Card
        {
            return AuthenticationStep::Authorize;
        }

        match (redirect_state, completed_step) {
            (RedirectState::InitialRequest, None) => AuthenticationStep::PreAuthenticate,
            // Frictionless / not enrolled / SKIP_3DS: the confirm came back terminal with no
            // next_action, so there is nothing to authenticate and nothing to retrieve.
            (RedirectState::InitialRequest, Some(AuthenticationStep::PreAuthenticate)) => {
                AuthenticationStep::Authorize
            }
            // The shopper has returned from the Airwallex-hosted page. Retrieve the intent — the
            // return-URL query string is advisory, the retrieved intent is the authority.
            (RedirectState::RedirectWithParams | RedirectState::RedirectWithoutParams, None) => {
                AuthenticationStep::PostAuthenticate
            }
            (
                RedirectState::RedirectWithParams | RedirectState::RedirectWithoutParams,
                Some(AuthenticationStep::PostAuthenticate),
            ) => AuthenticationStep::Authorize,
            _ => AuthenticationStep::Authorize,
        }
    }
}

