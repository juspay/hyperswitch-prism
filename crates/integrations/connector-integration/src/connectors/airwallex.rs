/// The Airwallex API version every `/pa/*` call is pinned to.
///
/// Airwallex documents `x-api-version` as per-call and, when it is absent, applies "your version
/// … stored in your account". That makes the wire contract a property of the merchant's account
/// settings rather than of this code: two merchants on the same UCS build can get two different
/// request shapes, and neither is observable from here. Pinning removes that entire class of
/// "works in our sandbox, 400s in production" failure.
///
/// `2024-06-14` is the earliest version whose 3DS behaviour is the modern one — a single
/// Airwallex-hosted `redirect_iframe` that performs the 3DS method call and the ACS challenge,
/// with no `confirm_continue` round trip — and it is stable through `2026-06-29`. The only later
/// change that touches this connector is `2026-06-30`, which moves
/// `payment_method.card.three_ds.return_url` to a top-level `return_url`; raising the pin past
/// that date means moving exactly one field.
pub(crate) const AIRWALLEX_API_VERSION: &str = "2024-06-14";

