macros::macro_connector_implementation!(
    connector_default_implementations: [get_content_type],
    connector: Airwallex,
    curl_request: Json(AirwallexPaymentRequest),
    curl_response: AirwallexPaymentsResponse,
    flow_name: Authorize,
    resource_common_data: PaymentFlowData,
    flow_request: PaymentsAuthorizeData<T>,
    flow_response: PaymentsResponseData,
    http_method: Post,
    generic_type: T,
    [PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize],
    other_functions: {
        fn get_headers(
            &self,
            req: &RouterDataV2<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>,
        ) -> CustomResult<Vec<(String, Maskable<String>)>, IntegrationError> {
            let access_token = req.resource_common_data.get_access_token()
                .change_context(IntegrationError::FailedToObtainAuthType { context: Default::default() })?;
            Ok(self.build_headers(&access_token))
        }
        fn get_url(
            &self,
            req: &RouterDataV2<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>,
        ) -> CustomResult<String, IntegrationError> {
            // 2-step flow: Authorize confirms the payment intent created by CreateOrder.
            let order_id = req.resource_common_data.connector_order_id
                .as_ref()
                .ok_or(IntegrationError::MissingRequiredField {
                    field_name: "connector_order_id",
                    context: IntegrationErrorContext {
                        additional_context: Some(
                            "Airwallex authorizes by confirming the PaymentIntent created by \
                             PaymentService/CreateOrder, so the intent id is required"
                                .to_string(),
                        ),
                        suggested_action: Some(
                            "Run PaymentService/CreateOrder first and send its connector_order_id \
                             on the Authorize request"
                                .to_string(),
                        ),
                        doc_url: Some(airwallex::AIRWALLEX_INTEGRATION_DOC_URL.to_string()),
                    },
                })?;
            let base_url = &req.resource_common_data.connectors.airwallex.base_url;
            // After the shopper returns from the Airwallex page the payment is already settled
            // there: the return leg only reads the intent (GET, see build_request_v2), it never
            // confirms a second time.
            if transformers::is_three_ds_return_leg(&req.request) {
                Ok(format!("{base_url}/pa/payment_intents/{order_id}"))
            } else {
                Ok(format!("{base_url}/pa/payment_intents/{order_id}/confirm"))
            }
        }
        fn build_request_v2(
            &self,
            req: &RouterDataV2<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>,
        ) -> CustomResult<Option<common_utils::request::Request>, IntegrationError> {
            if transformers::is_three_ds_return_leg(&req.request) {
                // Read-only return leg: GET the settled intent, no body.
                let url = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_url(self, req)?;
                let headers = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_headers(self, req)?;
                return Ok(Some(
                    common_utils::request::RequestBuilder::new()
                        .method(common_utils::request::Method::Get)
                        .url(&url)
                        .attach_default_headers()
                        .headers(headers)
                        .build(),
                ));
            }
            // Initial confirm: build the body first so the request-builder guards (external 3DS,
            // capture method, CIT customer) refuse before the URL's connector_order_id check.
            let request_data = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_request_body(self, req)?;
            let (body, typed_request_value) = match request_data {
                Some(data) => (
                    Some(data.content),
                    data.typed_request.map(|msv| msv.inner().clone()),
                ),
                None => (None, None),
            };
            let url = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_url(self, req)?;
            let headers = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_headers(self, req)?;
            let certificate = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_certificate(self, req)?;
            let certificate_key = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_certificate_key(self, req)?;
            let ca_certificate = ConnectorIntegrationV2::<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>::get_ca_certificate(self, req)?;
            Ok(Some(
                common_utils::request::RequestBuilder::new()
                    .method(common_utils::request::Method::Post)
                    .url(&url)
                    .attach_default_headers()
                    .headers(headers)
                    .set_optional_body(body)
                    .set_typed_connector_request(typed_request_value)
                    .add_certificate(certificate)
                    .add_certificate_key(certificate_key)
                    .add_ca_certificate_pem(ca_certificate)
                    .build(),
            ))
        }
        fn get_error_response_v2(
            &self,
            res: Response,
            event_builder: Option<&mut events::Event>,
            _connector_config: &ConnectorSpecificConfig,
        ) -> CustomResult<ErrorResponse, ConnectorError> {
            // A 4xx on confirm is a declined / invalid attempt; a 5xx leaves the outcome unknown.
            self.build_error_response_for_flow(
                res,
                event_builder,
                Some(FlowStatus::Payment(common_enums::AttemptStatus::Failure)),
            )
        }
    }
);

