impl<T: PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize>
    connector_types::IncomingWebhook for Airwallex<T>
{
    /// `x-signature` is the lowercase hex HMAC-SHA256 digest. Missing header ->
    /// `WebhookSignatureNotFound`; non-hex -> `WebhookVerificationSecretInvalid`.
    fn get_webhook_source_verification_signature(
        &self,
        request: &RequestDetails,
        _connector_webhook_secret: &ConnectorWebhookSecrets,
    ) -> Result<Vec<u8>, error_stack::Report<WebhookError>> {
        let signature = request
            .headers
            .get(headers::X_SIGNATURE)
            .ok_or_else(|| error_stack::report!(WebhookError::WebhookSignatureNotFound))
            .attach_printable("Missing x-signature header in Airwallex webhook")?;
        hex::decode(signature)
            .change_context(WebhookError::WebhookVerificationSecretInvalid)
            .attach_printable("Airwallex x-signature header is not hex")
    }

    /// Airwallex signs `x-timestamp ++ raw body`: the timestamp header string exactly as received
    /// (never re-rendered), immediately followed by the unmodified body bytes, no separator.
    /// No staleness check: Airwallex publishes no tolerance and retries for about three days.
    fn get_webhook_source_verification_message(
        &self,
        request: &RequestDetails,
        _connector_webhook_secret: &ConnectorWebhookSecrets,
    ) -> Result<Vec<u8>, error_stack::Report<WebhookError>> {
        let timestamp = request
            .headers
            .get(headers::X_TIMESTAMP)
            .ok_or_else(|| error_stack::report!(WebhookError::WebhookSignatureNotFound))
            .attach_printable("Missing x-timestamp header in Airwallex webhook")?;
        let mut message = Vec::with_capacity(timestamp.len() + request.body.len());
        message.extend_from_slice(timestamp.as_bytes());
        message.extend_from_slice(&request.body);
        Ok(message)
    }

    /// Fails closed: no (or an empty) webhook secret is an error, never a fallback to the API key.
    /// The secret is the subscription secret's raw UTF-8 bytes (not hex or base64 decoded).
    fn verify_webhook_source(
        &self,
        request: RequestDetails,
        connector_webhook_secret: Option<ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
    ) -> Result<bool, error_stack::Report<WebhookError>> {
        let connector_webhook_secret = connector_webhook_secret
            .filter(|secrets| !secrets.secret.is_empty())
            .ok_or_else(|| error_stack::report!(WebhookError::WebhookVerificationSecretNotFound))
            .attach_printable("Airwallex webhook secret is not configured")?;
        let signature =
            self.get_webhook_source_verification_signature(&request, &connector_webhook_secret)?;
        let message =
            self.get_webhook_source_verification_message(&request, &connector_webhook_secret)?;
        crypto::HmacSha256
            .verify_signature(&connector_webhook_secret.secret, &signature, &message)
            .change_context(WebhookError::WebhookSourceVerificationFailed)
    }

    fn get_event_type(
        &self,
        request: RequestDetails,
    ) -> Result<EventType, error_stack::Report<WebhookError>> {
        let envelope = airwallex::AirwallexWebhookEnvelope::from_body(&request.body)?;
        Ok(envelope.name.event_type())
    }

    fn get_webhook_event_reference(
        &self,
        request: RequestDetails,
    ) -> Result<Option<WebhookResourceReference>, error_stack::Report<WebhookError>> {
        let envelope = airwallex::AirwallexWebhookEnvelope::from_body(&request.body)?;
        airwallex::get_airwallex_webhook_reference(&envelope)
    }

    fn process_payment_webhook(
        &self,
        request: RequestDetails,
        _connector_webhook_secret: Option<ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
        _event_context: Option<EventContext>,
    ) -> Result<WebhookDetailsResponse, error_stack::Report<WebhookError>> {
        let envelope = airwallex::AirwallexWebhookEnvelope::from_body(&request.body)?;
        airwallex::get_airwallex_payment_webhook_details(&envelope, &request.body)
    }

    fn process_refund_webhook(
        &self,
        request: RequestDetails,
        _connector_webhook_secret: Option<ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
    ) -> Result<RefundWebhookDetailsResponse, error_stack::Report<WebhookError>> {
        let envelope = airwallex::AirwallexWebhookEnvelope::from_body(&request.body)?;
        airwallex::get_airwallex_refund_webhook_details(&envelope, &request.body)
    }

    fn process_dispute_webhook(
        &self,
        request: RequestDetails,
        _connector_webhook_secret: Option<ConnectorWebhookSecrets>,
        _connector_account_details: Option<ConnectorSpecificConfig>,
    ) -> Result<DisputeWebhookDetailsResponse, error_stack::Report<WebhookError>> {
        let envelope = airwallex::AirwallexWebhookEnvelope::from_body(&request.body)?;
        airwallex::get_airwallex_dispute_webhook_details(&envelope, &request.body)
    }

    fn get_webhook_resource_object(
        &self,
        request: RequestDetails,
    ) -> Result<Box<dyn hyperswitch_masking::ErasedMaskSerialize>, error_stack::Report<WebhookError>>
    {
        let envelope = airwallex::AirwallexWebhookEnvelope::from_body(&request.body)
            .change_context(WebhookError::WebhookResourceObjectNotFound)?;
        Ok(Box::new(envelope.data.object))
    }

    fn sample_webhook_body(&self) -> &'static [u8] {
        airwallex::AIRWALLEX_SAMPLE_WEBHOOK_BODY
    }
}

