#[cfg(test)]
mod tests {
    use common_enums::{AuthenticationType, PaymentMethod};
    use domain_types::payment_method_data::DefaultPCIHolder;
    use interfaces::connector_types::{AuthenticationStep, RedirectState, ValidationTrait};

    use super::Airwallex;

    /// Every `(RedirectState, Option<AuthenticationStep>)` pair the composite authorize loop can
    /// present. `Some(Authenticate)` is included precisely to prove that even if some other
    /// component fabricated it, Airwallex still refuses to run an authenticate leg.
    fn all_states() -> Vec<(RedirectState, Option<AuthenticationStep>)> {
        let redirect_states = [
            RedirectState::InitialRequest,
            RedirectState::RedirectWithParams,
            RedirectState::RedirectWithoutParams,
        ];
        let completed_steps = [
            None,
            Some(AuthenticationStep::PreAuthenticate),
            Some(AuthenticationStep::Authenticate),
            Some(AuthenticationStep::PostAuthenticate),
        ];
        redirect_states
            .into_iter()
            .flat_map(|redirect_state| {
                completed_steps
                    .into_iter()
                    .map(move |completed_step| (redirect_state, completed_step))
            })
            .collect()
    }

    /// Airwallex has no `Authenticate` counterpart on the pinned API version, and
    /// `PaymentAuthenticateV2` is not implemented. If any arm returned `Authenticate` the
    /// composite loop would call a flow that is still in `not_implemented:`.
    #[test]
    fn next_authentication_step_never_selects_authenticate() {
        let connector = Airwallex::<DefaultPCIHolder>::new();
        for (redirect_state, completed_step) in all_states() {
            let next = connector.next_authentication_step(
                AuthenticationType::ThreeDs,
                PaymentMethod::Card,
                redirect_state,
                completed_step,
            );
            assert_ne!(
                next,
                AuthenticationStep::Authenticate,
                "arm ({redirect_state:?}, {completed_step:?}) selected Authenticate"
            );
        }
    }

    /// `PostAuthenticate` never breaks the loop by itself, so the only way out is an arm that
    /// returns `Authorize`. Walking the machine from every starting state must reach it.
    #[test]
    fn next_authentication_step_always_terminates_at_authorize() {
        let connector = Airwallex::<DefaultPCIHolder>::new();
        for (redirect_state, initial_step) in all_states() {
            let mut completed_step = initial_step;
            let mut reached_authorize = false;
            // Four legs is already more than the state space; anything longer is a cycle.
            for _ in 0..4 {
                match connector.next_authentication_step(
                    AuthenticationType::ThreeDs,
                    PaymentMethod::Card,
                    redirect_state,
                    completed_step,
                ) {
                    AuthenticationStep::Authorize => {
                        reached_authorize = true;
                        break;
                    }
                    step => completed_step = Some(step),
                }
            }
            assert!(
                reached_authorize,
                "arm ({redirect_state:?}, {initial_step:?}) never terminated at Authorize"
            );
        }
    }

    /// The 3DS journey the spec describes: confirm, hosted redirect, retrieve, then the
    /// read-only Authorize.
    #[test]
    fn next_authentication_step_drives_the_two_call_three_ds_journey() {
        let connector = Airwallex::<DefaultPCIHolder>::new();
        let step = |redirect_state, completed_step| {
            connector.next_authentication_step(
                AuthenticationType::ThreeDs,
                PaymentMethod::Card,
                redirect_state,
                completed_step,
            )
        };

        assert_eq!(
            step(RedirectState::InitialRequest, None),
            AuthenticationStep::PreAuthenticate
        );
        // Frictionless: the confirm came back terminal, so go straight to the read.
        assert_eq!(
            step(
                RedirectState::InitialRequest,
                Some(AuthenticationStep::PreAuthenticate)
            ),
            AuthenticationStep::Authorize
        );
        // Challenge: the shopper is back from the hosted page — retrieve the intent.
        for redirect_state in [
            RedirectState::RedirectWithParams,
            RedirectState::RedirectWithoutParams,
        ] {
            assert_eq!(
                step(redirect_state, None),
                AuthenticationStep::PostAuthenticate
            );
            assert_eq!(
                step(redirect_state, Some(AuthenticationStep::PostAuthenticate)),
                AuthenticationStep::Authorize
            );
        }
    }

    /// The trio is opt-in: anything that is not a 3DS card payment keeps the inline Authorize
    /// path, so a bug in the trio cannot take non-3DS payments down.
    #[test]
    fn next_authentication_step_is_gated_on_three_ds_card() {
        let connector = Airwallex::<DefaultPCIHolder>::new();
        assert_eq!(
            connector.next_authentication_step(
                AuthenticationType::NoThreeDs,
                PaymentMethod::Card,
                RedirectState::InitialRequest,
                None,
            ),
            AuthenticationStep::Authorize
        );
        assert_eq!(
            connector.next_authentication_step(
                AuthenticationType::ThreeDs,
                PaymentMethod::Wallet,
                RedirectState::InitialRequest,
                None,
            ),
            AuthenticationStep::Authorize
        );
    }
}
