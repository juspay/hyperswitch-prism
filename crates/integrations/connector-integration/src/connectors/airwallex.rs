impl<T: PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize> ConnectorCommon
    for Airwallex<T>
{
    fn id(&self) -> &'static str {
        "airwallex"
    }

    fn get_currency_unit(&self) -> CurrencyUnit {
        CurrencyUnit::Base
    }

    fn common_get_content_type(&self) -> &'static str {
        "application/json"
    }

    fn base_url<'a>(&self, connectors: &'a Connectors) -> &'a str {
        connectors.airwallex.base_url.as_ref()
    }

    fn get_auth_header(
        &self,
        auth_type: &ConnectorSpecificConfig,
    ) -> CustomResult<Vec<(String, Maskable<String>)>, IntegrationError> {
        // Note: This method should not be used for OAuth-based connectors like Airwallex
        // Use build_payment_headers or build_refund_headers instead for OAuth flows
        // This method is only used for ServerAuthenticationToken flow
        let auth = airwallex::AirwallexAuthType::try_from(auth_type).change_context(
            IntegrationError::FailedToObtainAuthType {
                context: Default::default(),
            },
        )?;
        Ok(vec![
            (
                headers::X_API_KEY.to_string(),
                auth.api_key.expose().to_string().into_masked(),
            ),
            (
                headers::X_CLIENT_ID.to_string(),
                auth.client_id.expose().to_string().into_masked(),
            ),
        ])
    }

    fn build_error_response(
        &self,
        res: Response,
        event_builder: Option<&mut events::Event>,
        _connector_config: &ConnectorSpecificConfig,
    ) -> CustomResult<ErrorResponse, ConnectorError> {
        parse_airwallex_error_response(res, event_builder)
    }
}

/// Parses an Airwallex error body. `attempt_status` is left `None`: the flow-aware value is set by
/// `build_error_response_for_flow` in the flows that override `get_error_response_v2`.
fn parse_airwallex_error_response(
    res: Response,
    event_builder: Option<&mut events::Event>,
) -> CustomResult<ErrorResponse, ConnectorError> {
    let response: airwallex::AirwallexErrorResponse = res
        .response
        .parse_struct("AirwallexErrorResponse")
        .change_context(crate::utils::response_deserialization_fail(
            res.status_code,
            "airwallex: response body did not match the expected format; confirm API version and connector documentation.",
        ))?;

    with_error_response_body!(event_builder, response);
    let typed = macros::serialize_typed_connector_payload(&response, "typed_connector_response");

    let error_message = match response.source {
        Some(ref source) => format!("{}; {}", response.message, source),
        None => response.message.clone(),
    };

    // Issuer / scheme code, when Airwallex relays one (HS parity).
    let network_error_message = response
        .provider_original_response_code
        .as_deref()
        .and_then(airwallex::map_issuer_code_to_message);

    Ok(ErrorResponse {
        status_code: res.status_code,
        code: response.code,
        message: error_message.clone(),
        reason: Some(error_message),
        attempt_status: None,
        connector_transaction_id: None,
        network_decline_code: response.provider_original_response_code,
        network_advice_code: None,
        network_error_message,
        typed_connector_response: typed,
        raw_connector_response: None,
        raw_connector_request: None,
        typed_connector_request: None,
    })
}

