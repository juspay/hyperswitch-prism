macros::macro_connector_implementation!(
    connector_default_implementations: [get_content_type, get_error_response_v2],
    connector: Airwallex,
    curl_request: Json(AirwallexAuthorizeRequest),
    curl_response: AirwallexPaymentsResponse,
    flow_name: Authorize,
    resource_common_data: PaymentFlowData,
    flow_request: PaymentsAuthorizeData<T>,
    flow_response: PaymentsResponseData,
    http_method: Post,
    generic_type: T,
    [PaymentMethodDataTypes + Debug + Sync + Send + 'static + Serialize],
    other_functions: {
        fn get_headers(
            &self,
            req: &RouterDataV2<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>,
        ) -> CustomResult<Vec<(String, Maskable<String>)>, IntegrationError> {
            let access_token = req.resource_common_data.get_access_token()
                .change_context(IntegrationError::FailedToObtainAuthType { context: Default::default() })?;
            Ok(self.build_headers(&access_token))
        }
        fn get_url(
            &self,
            req: &RouterDataV2<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>,
        ) -> CustomResult<String, IntegrationError> {
            // 2-step flow: Authorize confirms the payment intent created by CreateOrder.
            // Get order_id from reference_id (stored after CreateOrder via set_order_reference_id).
            let order_id = req.resource_common_data.connector_order_id
                .as_ref()
                .ok_or(IntegrationError::MissingRequiredField { field_name: "connector_order_id", context: Default::default() })?;
            let base_url = &req.resource_common_data.connectors.airwallex.base_url;
            // When HS re-invokes Authorize after a card 3DS redirect, the payment has ALREADY been
            // authorized by the first `confirm` — on the pinned API version Airwallex's own guide
            // says to "Retrieve PaymentIntent to confirm status". So the return leg is a bodyless
            // retrieve, not a second confirm and not the removed `confirm_continue`. Same gate as
            // `build_request_v2` below, so the URL and the HTTP method cannot disagree.
            if transformers::is_card_three_ds_continue(&req.request) {
                Ok(format!("{base_url}/pa/payment_intents/{order_id}"))
            } else {
                Ok(format!("{base_url}/pa/payment_intents/{order_id}/confirm"))
            }
        }
        /// `get_http_method` only sees `&self`, so the 3DS return leg's `GET` has to be chosen
        /// here: it is a retrieve of the intent the first `confirm` already authorized, and it
        /// carries no body. Everything else keeps the macro-generated `POST` + JSON body.
        fn build_request_v2(
            &self,
            req: &RouterDataV2<Authorize, PaymentFlowData, PaymentsAuthorizeData<T>, PaymentsResponseData>,
        ) -> CustomResult<Option<common_utils::request::Request>, IntegrationError> {
            use common_utils::request::{Method, RequestBuilder};

            let is_three_ds_return_leg = transformers::is_card_three_ds_continue(&req.request);

            let builder = RequestBuilder::new()
                .method(if is_three_ds_return_leg { Method::Get } else { Method::Post })
                .url(self.get_url(req)?.as_str())
                .attach_default_headers()
                .headers(self.get_headers(req)?);

            let builder = if is_three_ds_return_leg {
                builder
            } else {
                let request_data = self.get_request_body(req)?;
                let (body, typed_request_value) = match request_data {
                    Some(data) => (Some(data.content), data.typed_request.map(|msv| msv.inner().clone())),
                    None => (None, None),
                };
                builder
                    .set_optional_body(body)
                    .set_typed_connector_request(typed_request_value)
            };

            Ok(Some(builder.build()))
        }
    }
);

