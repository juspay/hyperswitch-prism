#[derive(Debug, Serialize)]
pub struct PlaidLinkTokenRequest {
    pub client_id: Secret<String>,
    pub secret: Secret<String>,
    pub client_name: String,
    pub user: PlaidUser,
    pub products: Vec<String>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub country_codes: Vec<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub language: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub redirect_uri: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub webhook: Option<String>,
}

#[derive(Debug, Serialize)]
pub struct PlaidUser {
    pub client_user_id: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub legal_name: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub email_address: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub phone_number: Option<String>,
}

impl<T: PaymentMethodDataTypes + std::fmt::Debug + Sync + Send + 'static + Serialize>
    TryFrom<
        PlaidRouterData<
            RouterDataV2<
                domain_types::connector_flow::ClientAuthenticationToken,
                MerchantAuthenticationFlowData,
                ClientAuthenticationTokenRequestData,
                PaymentsResponseData,
            >,
            T,
        >,
    > for PlaidLinkTokenRequest
{
    type Error = error_stack::Report<IntegrationError>;

    fn try_from(
        item: PlaidRouterData<
            RouterDataV2<
                domain_types::connector_flow::ClientAuthenticationToken,
                MerchantAuthenticationFlowData,
                ClientAuthenticationTokenRequestData,
                PaymentsResponseData,
            >,
            T,
        >,
    ) -> Result<Self, Self::Error> {
        let auth = PlaidAuthType::try_from(&item.router_data.connector_config)?;
        let req = &item.router_data.request;

        // client_name comes from connector_feature_data["client_name"] or a default
        let client_name = item
            .router_data
            .resource_common_data
            .connector_feature_data
            .as_ref()
            .and_then(|v| {
                v.peek()
                    .as_object()
                    .and_then(|o| o.get("client_name"))
                    .and_then(|v| v.as_str())
                    .map(|s| s.to_owned())
            })
            .unwrap_or_else(|| "Hyperswitch".to_owned());

        let user = PlaidUser {
            client_user_id: req
                .customer_id
                .as_ref()
                .map(|id| id.get_string_repr().to_owned())
                .unwrap_or_else(|| {
                    item.router_data
                        .resource_common_data
                        .connector_request_reference_id
                        .clone()
                }),
            legal_name: req.customer_name.as_ref().map(|n| n.peek().to_owned()),
            email_address: req.email.as_ref().map(|e| e.peek().to_owned()),
            phone_number: None,
        };

        let country_codes = req
            .country_codes
            .iter()
            .map(|c| c.to_string())
            .collect::<Vec<_>>();

        Ok(Self {
            client_id: auth.client_id,
            secret: auth.secret,
            client_name,
            user,
            products: vec!["auth".to_owned()],
            country_codes,
            language: req.locale.clone(),
            redirect_uri: item.router_data.resource_common_data.return_url.clone(),
            webhook: req.webhook_url.clone(),
        })
    }
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidLinkTokenResponse {
    pub link_token: Secret<String>,
    pub expiration: Option<String>,
    pub hosted_link_url: Option<String>,
    pub request_id: String,
}

impl
    TryFrom<
        ResponseRouterData<
            PlaidLinkTokenResponse,
            RouterDataV2<
                domain_types::connector_flow::ClientAuthenticationToken,
                MerchantAuthenticationFlowData,
                ClientAuthenticationTokenRequestData,
                PaymentsResponseData,
            >,
        >,
    >
    for RouterDataV2<
        domain_types::connector_flow::ClientAuthenticationToken,
        MerchantAuthenticationFlowData,
        ClientAuthenticationTokenRequestData,
        PaymentsResponseData,
    >
{
    type Error = error_stack::Report<ConnectorError>;

    fn try_from(
        item: ResponseRouterData<
            PlaidLinkTokenResponse,
            Self,
        >,
    ) -> Result<Self, Self::Error> {
        let res = item.response;

        let expires_in_seconds: Option<i64> = res.expiration.as_deref().and_then(|exp| {
            time::OffsetDateTime::parse(exp, &time::format_description::well_known::Rfc3339)
                .ok()
                .map(|expiry_time| {
                    let now = time::OffsetDateTime::now_utc();
                    (expiry_time - now).whole_seconds()
                })
        });

        let plaid_auth_response = PlaidClientAuthenticationResponse {
            link_token: res.link_token,
            expires_in_seconds,
            hosted_link_url: res.hosted_link_url,
        };

        let session_data = ClientAuthenticationTokenData::Plaid(Box::new(plaid_auth_response));

        Ok(Self {
            response: Ok(PaymentsResponseData::ClientAuthenticationTokenResponse {
                session_data,
                status_code: item.http_code,
            }),
            ..item.router_data
        })
    }
}

