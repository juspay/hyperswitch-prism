#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidAuthGetResponse {
    pub accounts: Vec<PlaidAccount>,
    pub numbers: PlaidNumbers,
    pub request_id: String,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidAccount {
    pub account_id: String,
    pub name: String,
    pub subtype: Option<String>,
    pub balances: PlaidBalances,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidBalances {
    pub current: Option<f64>,
    pub available: Option<f64>,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidNumbers {
    #[serde(default)]
    pub ach: Vec<PlaidAchNumbers>,
    #[serde(default)]
    pub bacs: Vec<PlaidBacsNumbers>,
    #[serde(default)]
    pub international: Vec<PlaidSepaNumbers>,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidAchNumbers {
    pub account_id: String,
    pub account: Secret<String>,
    pub routing: String,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidBacsNumbers {
    pub account_id: String,
    pub account: Secret<String>,
    pub sort_code: String,
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidSepaNumbers {
    pub account_id: String,
    pub iban: Secret<String>,
    pub bic: Option<Secret<String>>,
}

impl
    TryFrom<
        ResponseRouterData<
            PlaidAuthGetResponse,
            RouterDataV2<
                domain_types::connector_flow::GetPaymentMethod,
                PaymentFlowData,
                GetPaymentMethodData,
                GetPaymentMethodResponseData,
            >,
        >,
    >
    for RouterDataV2<
        domain_types::connector_flow::GetPaymentMethod,
        PaymentFlowData,
        GetPaymentMethodData,
        GetPaymentMethodResponseData,
    >
{
    type Error = error_stack::Report<ConnectorError>;

    fn try_from(
        item: ResponseRouterData<
            PlaidAuthGetResponse,
            Self,
        >,
    ) -> Result<Self, Self::Error> {
        let res = item.response;

        // Build lookup maps from account_id → routing details
        let ach_map: std::collections::HashMap<_, _> = res
            .numbers
            .ach
            .into_iter()
            .map(|n| (n.account_id.clone(), n))
            .collect();
        let bacs_map: std::collections::HashMap<_, _> = res
            .numbers
            .bacs
            .into_iter()
            .map(|n| (n.account_id.clone(), n))
            .collect();
        let sepa_map: std::collections::HashMap<_, _> = res
            .numbers
            .international
            .into_iter()
            .map(|n| (n.account_id.clone(), n))
            .collect();

        let accounts: Vec<BankAccount> = res
            .accounts
            .into_iter()
            .map(|acct| {
                let bank_type = acct.subtype.as_deref().and_then(plaid_subtype_to_bank_type);

                let balance = acct.balances.current.map(|amt| common_utils::types::Money {
                    amount: common_utils::types::MinorUnit::new(
                        f64::round(amt * 100.0) as i64,
                    ),
                    currency: common_enums::Currency::USD,
                });
                let available_balance =
                    acct.balances
                        .available
                        .map(|amt| common_utils::types::Money {
                            amount: common_utils::types::MinorUnit::new(
                                f64::round(amt * 100.0) as i64,
                            ),
                            currency: common_enums::Currency::USD,
                        });

                // Prefer ACH → BACS → SEPA in that order
                let account_details = if let Some(ach) = ach_map.get(&acct.account_id) {
                    Some(BankAccountRoutingDetails::Ach(BankAccountAchDetails {
                        account_number: ach.account.clone(),
                        routing_number: Secret::new(ach.routing.clone()),
                    }))
                } else if let Some(bacs) = bacs_map.get(&acct.account_id) {
                    Some(BankAccountRoutingDetails::Bacs(BankAccountBacsDetails {
                        account_number: bacs.account.clone(),
                        sort_code: Secret::new(bacs.sort_code.clone()),
                    }))
                } else {
                    sepa_map.get(&acct.account_id).map(|sepa| {
                        BankAccountRoutingDetails::Sepa(BankAccountSepaDetails {
                            iban: sepa.iban.clone(),
                            bic: sepa.bic.clone(),
                        })
                    })
                };

                BankAccount {
                    account_name: acct.name,
                    account_id: Secret::new(acct.account_id),
                    bank_type,
                    bank_holder_type: None,
                    balance,
                    available_balance,
                    account_details,
                }
            })
            .collect();

        Ok(Self {
            response: Ok(GetPaymentMethodResponseData {
                merchant_payment_method_id: None,
                connector_payment_method_id: None,
                customer: None,
                payment_method_details: Some(PaymentMethodDetails::BankAccount(
                    BankAccountDetails { accounts },
                )),
                status_code: item.http_code,
            }),
            ..item.router_data
        })
    }
}

/// Map Plaid account subtype strings to the domain `BankType` enum.
fn plaid_subtype_to_bank_type(subtype: &str) -> Option<BankType> {
    match subtype {
        "checking" => Some(BankType::Checking),
        "savings" => Some(BankType::Savings),
        _ => None,
    }
}

