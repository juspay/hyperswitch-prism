#[derive(Debug, Serialize)]
pub struct PlaidUser {
    pub client_user_id: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub legal_name: Option<Secret<String>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub email_address: Option<Email>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub phone_number: Option<Secret<String>>,
}

impl<T: PaymentMethodDataTypes + std::fmt::Debug + Sync + Send + 'static + Serialize>
    TryFrom<
        PlaidRouterData<
            RouterDataV2<
                domain_types::connector_flow::ClientAuthenticationToken,
                MerchantAuthenticationFlowData,
                ClientAuthenticationTokenRequestData,
                PaymentsResponseData,
            >,
            T,
        >,
    > for PlaidLinkTokenRequest
{
    type Error = error_stack::Report<IntegrationError>;

    fn try_from(
        item: PlaidRouterData<
            RouterDataV2<
                domain_types::connector_flow::ClientAuthenticationToken,
                MerchantAuthenticationFlowData,
                ClientAuthenticationTokenRequestData,
                PaymentsResponseData,
            >,
            T,
        >,
    ) -> Result<Self, Self::Error> {
        let auth = PlaidAuthType::try_from(&item.router_data.connector_config)?;
        let req = &item.router_data.request;

        let client_name = auth.client_name.ok_or_else(|| {
            report!(IntegrationError::MissingRequiredField {
                field_name: "client_name",
                context: IntegrationErrorContext {
                    additional_context: Some(
                        "client_name must be set in the Plaid connector config".to_owned(),
                    ),
                    suggested_action: Some(
                        "Set client_name in the Plaid connector config".to_owned(),
                    ),
                    doc_url: Some(
                        "https://plaid.com/docs/api/tokens/#linktokencreate-client_name".to_owned(),
                    ),
                },
            })
        })?;

        let customer = req.customer.as_ref().ok_or_else(|| {
            report!(IntegrationError::MissingRequiredField {
                field_name: "customer",
                context: IntegrationErrorContext {
                    additional_context: Some(
                        "customer is required for Plaid Link token creation".to_owned()
                    ),
                    suggested_action: Some(
                        "Provide customer details including customer_id in the request".to_owned()
                    ),
                    doc_url: Some(
                        "https://plaid.com/docs/api/tokens/#linktokencreate-user".to_owned()
                    ),
                },
            })
        })?;

        let user = PlaidUser {
            client_user_id: customer.get_customer_id()?.get_string_repr().to_owned(),
            legal_name: customer.customer_name.clone(),
            email_address: customer.customer_email.clone(),
            phone_number: customer.customer_phone_number.clone(),
        };

        let country_codes = req
            .country_codes
            .iter()
            .map(|country_code| country_code.to_string())
            .collect::<Vec<_>>();

        if country_codes.is_empty() {
            return Err(report!(IntegrationError::MissingRequiredField {
                field_name: "country_codes",
                context: IntegrationErrorContext {
                    additional_context: Some(
                        "Plaid /link/token/create requires at least one country code".to_owned(),
                    ),
                    suggested_action: Some(
                        "Set country_codes in the Authenticator domain context, e.g. [\"US\"]"
                            .to_owned(),
                    ),
                    doc_url: Some(
                        "https://plaid.com/docs/api/tokens/#linktokencreate-country-codes"
                            .to_owned(),
                    ),
                },
            }));
        }

        Ok(Self {
            client_id: auth.client_id,
            secret: auth.secret,
            client_name,
            user,
            products: vec!["auth".to_owned()],
            country_codes,
            language: req.locale.clone(),
            redirect_uri: item.router_data.resource_common_data.return_url.clone(),
            webhook: req.webhook_url.clone(),
        })
    }
}

#[derive(Debug, Deserialize, Serialize)]
pub struct PlaidLinkTokenResponse {
    pub link_token: Secret<String>,
    pub expiration: Option<String>,
    pub hosted_link_url: Option<String>,
    pub request_id: String,
}

impl TryFrom<ResponseRouterData<PlaidLinkTokenResponse, Self>>
    for RouterDataV2<
        domain_types::connector_flow::ClientAuthenticationToken,
        MerchantAuthenticationFlowData,
        ClientAuthenticationTokenRequestData,
        PaymentsResponseData,
    >
{
    type Error = error_stack::Report<ConnectorError>;

    fn try_from(
        item: ResponseRouterData<PlaidLinkTokenResponse, Self>,
    ) -> Result<Self, Self::Error> {
        let res = item.response;

        let expires_in_seconds: Option<i64> = res.expiration.as_deref().and_then(|exp| {
            time::OffsetDateTime::parse(exp, &time::format_description::well_known::Rfc3339)
                .inspect_err(|e| {
                    tracing::debug!(
                        error = %e,
                        raw_expiration = %exp,
                        "Plaid link_token expiration is not RFC3339; expires_in_seconds will be omitted"
                    );
                })
                .ok()
                .and_then(|expiry_time| {
                    let secs = (expiry_time - time::OffsetDateTime::now_utc()).whole_seconds();
                    if secs > 0 { Some(secs) } else { None }
                })
        });

        let plaid_auth_response = PlaidClientAuthenticationResponse {
            link_token: res.link_token,
            expires_in_seconds,
            hosted_link_url: res.hosted_link_url,
        };

        let session_data = ClientAuthenticationTokenData::Plaid(Box::new(plaid_auth_response));

        Ok(Self {
            response: Ok(PaymentsResponseData::ClientAuthenticationTokenResponse {
                session_data,
                status_code: item.http_code,
            }),
            ..item.router_data
        })
    }
}

