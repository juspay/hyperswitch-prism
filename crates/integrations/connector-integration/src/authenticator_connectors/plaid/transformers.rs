#[derive(Debug)]
pub struct PlaidAuthType {
    pub client_id: Secret<String>,
    pub secret: Secret<String>,
    pub client_name: Option<String>,
}

impl TryFrom<&ConnectorSpecificConfig> for PlaidAuthType {
    type Error = error_stack::Report<IntegrationError>;

    fn try_from(config: &ConnectorSpecificConfig) -> Result<Self, Self::Error> {
        match config {
            ConnectorSpecificConfig::Plaid {
                client_id,
                secret,
                client_name,
                ..
            } => Ok(Self {
                client_id: client_id.clone(),
                secret: secret.clone(),
                client_name: client_name.clone(),
            }),
            _ => Err(report!(IntegrationError::FailedToObtainAuthType {
                context: IntegrationErrorContext {
                    additional_context: Some("Expected ConnectorSpecificConfig::Plaid".to_owned()),
                    suggested_action: Some(
                        "Ensure the connector config provides Plaid client_id and secret"
                            .to_owned(),
                    ),
                    doc_url: Some("https://plaid.com/docs/api/".to_owned()),
                }
            })),
        }
    }
}

