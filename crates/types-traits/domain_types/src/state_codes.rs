//! Generated from Hyperswitch `common_enums::*StatesAbbreviation` and
//! `hyperswitch_connectors::utils` `ForeignTryFrom<String>` impls so that UCS
//! produces the same state codes as Hyperswitch. US and CA are handled by
//! `convert_us_state_to_code` / `convert_canada_state_to_code`.

use std::sync::LazyLock;

use regex::Regex;
use unicode_normalization::UnicodeNormalization;

/// NFKD-normalize, lowercase and strip everything except `[a-z0-9]`.
fn normalize_state_name(value: &str) -> String {
    static NON_ALPHANUMERIC: LazyLock<Option<Regex>> =
        LazyLock::new(|| Regex::new(r"[^a-z0-9]").ok());
    let lowercase_value = value.nfkd().collect::<String>().to_lowercase();
    match NON_ALPHANUMERIC.as_ref() {
        Some(regex) => regex.replace_all(&lowercase_value, "").to_string(),
        None => lowercase_value,
    }
}

